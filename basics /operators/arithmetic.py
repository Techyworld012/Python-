# arithmetic operators 

print(2+3)  # addition operator , output is 5
print(2-3)  # subtraction operator , output is -1
print(2*3)  # multiplication operator , output is 6
print(2/3)  # division operator , output is 0.666666666
print(14%3)  # modulus operator , output is 1
print(14//3)  # floor division operator , output is 4
print(2**3)  # exponent operator , output is 8  

# comparison Operators 

print(2>3)  # greater than operator , output is False
print(2<3)  # less than operator , output is True
print(2>=3)  # greater than or equal to operator , output is False
print(2<=3)  # less than or equal to operator , output is True
print(2==3)  # equal to operator , output is False
print(2!=3)  # not equal to operator , output is True