print(a[1:5])  # from 1 to 4 

print(a[0:3])  # from 0 to 2 

print(a[:3])   # from starting to 2 

print(a[2:])  # from index 2 to ending 

print("negative")

print(a[-4:-1])  # print  -4 to -2   ,, undetstand this 

print(a[:-1])    

